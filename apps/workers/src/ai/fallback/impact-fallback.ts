/**
 * @file impact-fallback.ts
 * Deterministic fallback generator for Impact Explanation (Phase 9 Step 66).
 *
 * Produces a schema-valid, evidence-grounded AIExplanationOutputDto directly from
 * a trusted ImpactExplanationContext without calling any LLM or external provider.
 */

import type {
  AIExplanationClaimDto,
  AIExplanationConfidence,
  AIExplanationOutputDto,
} from "@fluxora/shared-types";

import type { BoundedFinding, ImpactExplanationContext } from "../context/types.ts";
import {
  IMPACT_EXPLANATION_LIMITS,
  IMPACT_EXPLANATION_OUTPUT_SCHEMA_VERSION,
} from "../structured-output/constants.ts";
import { validateImpactExplanationOutput } from "../structured-output/validator.ts";
import {
  IMPACT_FALLBACK_PROMPT_VERSION,
  type FallbackGenerationResult,
} from "./types.ts";

function truncateText(text: string, maxLength: number): string {
  if (text.length <= maxLength) {
    return text;
  }
  if (maxLength <= 3) {
    return text.slice(0, maxLength);
  }
  return `${text.slice(0, maxLength - 3)}...`;
}

function collectUniqueFindings(context: ImpactExplanationContext): readonly BoundedFinding[] {
  const seen = new Set<string>();
  const ordered: BoundedFinding[] = [];
  const groups: readonly (readonly BoundedFinding[])[] = [
    context.directImpact,
    context.downstreamImpact,
    context.affectedApis,
    context.affectedEvents,
    context.affectedServices,
  ];

  for (const group of groups) {
    for (const finding of group) {
      if (!seen.has(finding.nodeId)) {
        seen.add(finding.nodeId);
        ordered.push(finding);
      }
    }
  }

  return ordered;
}

function deriveConfidence(
  citedFindings: readonly BoundedFinding[],
  context: ImpactExplanationContext,
  omittedWithoutEvidenceCount: number,
): AIExplanationConfidence {
  if (citedFindings.length === 0) {
    return "low";
  }

  let minConfidence = 1;
  let sumConfidence = 0;
  for (const finding of citedFindings) {
    if (finding.confidence < minConfidence) {
      minConfidence = finding.confidence;
    }
    sumConfidence += finding.confidence;
  }
  const avgConfidence = sumConfidence / citedFindings.length;

  if (avgConfidence < 0.5 || minConfidence < 0.4) {
    return "low";
  }

  if (
    context.truncated ||
    context.unresolvedFiles.length > 0 ||
    omittedWithoutEvidenceCount > 0 ||
    minConfidence < 0.8
  ) {
    return "medium";
  }

  return "high";
}

function buildCaveats(
  context: ImpactExplanationContext,
  omittedWithoutEvidenceCount: number,
  abstained: boolean,
): readonly string[] {
  const caveats: string[] = [
    "Generated by deterministic fallback without an AI model.",
  ];

  if (abstained) {
    caveats.push(
      "Deterministic fallback abstained from making factual claims because no verified evidence records were available.",
    );
  }

  if (context.truncated) {
    const reasonText = context.truncationReason ?? "context budget limits exceeded";
    caveats.push(
      truncateText(
        `Impact context is truncated: ${reasonText} (omitted findings: ${context.truncation.omittedFindingsCount}, omitted evidence: ${context.truncation.omittedEvidenceCount}).`,
        IMPACT_EXPLANATION_LIMITS.MAX_CAVEAT_TEXT_LENGTH,
      ),
    );
  }

  if (context.unresolvedFiles.length > 0) {
    const preview = context.unresolvedFiles
      .slice(0, 5)
      .map((f) => `${f.path} (${f.reason})`)
      .join("; ");
    const suffix = context.unresolvedFiles.length > 5 ? "; ..." : "";
    caveats.push(
      truncateText(
        `${context.unresolvedFiles.length} changed file(s) remain unresolved: ${preview}${suffix}.`,
        IMPACT_EXPLANATION_LIMITS.MAX_CAVEAT_TEXT_LENGTH,
      ),
    );
  }

  if (!abstained && omittedWithoutEvidenceCount > 0) {
    caveats.push(
      `${omittedWithoutEvidenceCount} finding(s) lacked verified evidence records and were excluded from factual claims.`,
    );
  }

  return caveats.slice(0, IMPACT_EXPLANATION_LIMITS.MAX_CAVEATS_COUNT);
}

/**
 * Generates a deterministic, evidence-grounded fallback explanation for an ImpactAnalysis.
 */
export function generateImpactExplanationFallback(
  context: ImpactExplanationContext,
): FallbackGenerationResult {
  const allowedSet = new Set(context.allowedEvidenceIds);
  const uniqueFindings = collectUniqueFindings(context);

  const claims: AIExplanationClaimDto[] = [];
  const citedFindings: BoundedFinding[] = [];
  const usedEvidenceIds = new Set<string>();
  let omittedWithoutEvidenceCount = 0;

  for (const finding of uniqueFindings) {
    const validIds: string[] = [];
    const seenIds = new Set<string>();
    for (const id of finding.evidenceIds) {
      if (allowedSet.has(id) && !seenIds.has(id)) {
        seenIds.add(id);
        validIds.push(id);
        if (validIds.length >= IMPACT_EXPLANATION_LIMITS.MAX_EVIDENCE_IDS_PER_CLAIM) {
          break;
        }
      }
    }

    if (validIds.length === 0) {
      omittedWithoutEvidenceCount += 1;
      continue;
    }

    if (claims.length < IMPACT_EXPLANATION_LIMITS.MAX_CLAIMS_COUNT) {
      const scopeLabel =
        finding.depth === 0 ? "Direct impact" : `Downstream impact (depth ${finding.depth})`;
      const locationPart = finding.filePath ? ` at ${finding.filePath}` : "";
      const claimText = truncateText(
        `${scopeLabel}: ${finding.nodeType} '${finding.name}'${locationPart} (confidence ${finding.confidence.toFixed(2)}).`,
        IMPACT_EXPLANATION_LIMITS.MAX_CLAIM_TEXT_LENGTH,
      );

      claims.push({
        text: claimText,
        evidence_ids: validIds,
      });
      citedFindings.push(finding);
      for (const id of validIds) {
        usedEvidenceIds.add(id);
      }
    }
  }

  const abstained = allowedSet.size === 0 || claims.length === 0;
  const confidence = abstained
    ? "low"
    : deriveConfidence(citedFindings, context, omittedWithoutEvidenceCount);
  const caveats = buildCaveats(context, omittedWithoutEvidenceCount, abstained);

  let summary: string;
  if (abstained) {
    summary = truncateText(
      `Unable to provide an evidence-grounded impact explanation because no verified evidence records are available in the deterministic context (${context.executionMetrics.totalAffectedNodes} affected node(s) recorded).`,
      IMPACT_EXPLANATION_LIMITS.MAX_SUMMARY_LENGTH,
    );
  } else {
    const parts = [
      `Deterministic impact summary: ${context.directImpact.length} direct impact finding(s), ${context.downstreamImpact.length} downstream finding(s), ${context.affectedApis.length} affected API(s), ${context.affectedEvents.length} affected event(s), and ${context.affectedServices.length} affected service(s) (${context.executionMetrics.totalAffectedNodes} total affected nodes, max depth ${context.executionMetrics.maxDepthReached}).`,
    ];
    if (context.truncated) {
      parts.push("Context was truncated; additional findings may exist.");
    }
    if (context.unresolvedFiles.length > 0) {
      parts.push(`${context.unresolvedFiles.length} changed file(s) remain unresolved.`);
    }
    summary = truncateText(parts.join(" "), IMPACT_EXPLANATION_LIMITS.MAX_SUMMARY_LENGTH);
  }

  const output: AIExplanationOutputDto = {
    summary,
    claims: abstained ? [] : claims,
    confidence,
    caveats,
  };

  // Self-check invariant: fallback output must always satisfy the canonical validator
  const check = validateImpactExplanationOutput(JSON.stringify(output), context.allowedEvidenceIds);
  if (!check.success) {
    throw new Error(
      `Deterministic impact fallback produced invalid output: ${check.errors.map((e) => e.code).join(", ")}`,
    );
  }

  return {
    output,
    schemaVersion: IMPACT_EXPLANATION_OUTPUT_SCHEMA_VERSION,
    promptVersion: IMPACT_FALLBACK_PROMPT_VERSION,
    abstained,
    usedEvidenceIds: Array.from(usedEvidenceIds),
    omittedWithoutEvidenceCount,
  };
}
