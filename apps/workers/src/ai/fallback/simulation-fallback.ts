/**
 * @file simulation-fallback.ts
 * Deterministic fallback generator for Simulation Narration (Phase 9 Step 66).
 *
 * Produces a schema-valid, evidence-grounded AIExplanationOutputDto directly from
 * a trusted SimulationNarrationContext without calling any LLM or external provider.
 */

import type {
  AIExplanationClaimDto,
  AIExplanationConfidence,
  AIExplanationOutputDto,
} from "@fluxora/shared-types";

import type {
  BoundedSimulationNodeResult,
  SimulationNarrationContext,
} from "../simulation-context/types.ts";
import {
  IMPACT_EXPLANATION_LIMITS,
  SIMULATION_NARRATION_OUTPUT_SCHEMA_VERSION,
} from "../structured-output/constants.ts";
import { validateSimulationNarrationOutput } from "../structured-output/simulation-validator.ts";
import {
  SIMULATION_FALLBACK_PROMPT_VERSION,
  type FallbackGenerationResult,
} from "./types.ts";

function truncateText(text: string, maxLength: number): string {
  if (text.length <= maxLength) {
    return text;
  }
  if (maxLength <= 3) {
    return text.slice(0, maxLength);
  }
  return `${text.slice(0, maxLength - 3)}...`;
}

function deriveConfidence(
  citedResults: readonly BoundedSimulationNodeResult[],
  context: SimulationNarrationContext,
  omittedWithoutEvidenceCount: number,
): AIExplanationConfidence {
  if (citedResults.length === 0) {
    return "low";
  }

  let minConfidence = 1;
  let sumConfidence = 0;
  for (const r of citedResults) {
    if (r.confidence < minConfidence) {
      minConfidence = r.confidence;
    }
    sumConfidence += r.confidence;
  }
  const avgConfidence = sumConfidence / citedResults.length;

  if (avgConfidence < 0.5 || minConfidence < 0.4) {
    return "low";
  }

  if (
    context.truncated ||
    omittedWithoutEvidenceCount > 0 ||
    context.executionMetrics.cappedCount > 0 ||
    minConfidence < 0.8
  ) {
    return "medium";
  }

  return "high";
}

function buildCaveats(
  context: SimulationNarrationContext,
  omittedWithoutEvidenceCount: number,
  abstained: boolean,
): readonly string[] {
  const caveats: string[] = [
    "Generated by deterministic fallback without an AI model.",
    truncateText(
      `Synthetic scenario simulation ('${context.scenario.name}', failureType='${context.scenario.failureType}'): represents deterministic rule propagation, not live production telemetry.`,
      IMPACT_EXPLANATION_LIMITS.MAX_CAVEAT_TEXT_LENGTH,
    ),
  ];

  if (abstained) {
    caveats.push(
      "Deterministic fallback abstained from making factual claims because no verified simulation_state evidence records were available.",
    );
  }

  if (context.truncated) {
    const reasonText = context.truncationReason ?? "context budget limits exceeded";
    caveats.push(
      truncateText(
        `Simulation context is truncated: ${reasonText} (omitted results: ${context.truncation.omittedResultsCount}, omitted evidence: ${context.truncation.omittedEvidenceCount}).`,
        IMPACT_EXPLANATION_LIMITS.MAX_CAVEAT_TEXT_LENGTH,
      ),
    );
  }

  if (context.executionMetrics.cappedCount > 0) {
    caveats.push(
      `${context.executionMetrics.cappedCount} node result(s) reached propagation depth or confidence caps.`,
    );
  }

  if (!abstained && omittedWithoutEvidenceCount > 0) {
    caveats.push(
      `${omittedWithoutEvidenceCount} simulation result(s) lacked verified evidence records and were excluded from factual claims.`,
    );
  }

  return caveats.slice(0, IMPACT_EXPLANATION_LIMITS.MAX_CAVEATS_COUNT);
}

/**
 * Generates a deterministic, evidence-grounded fallback narration for a Simulation.
 */
export function generateSimulationNarrationFallback(
  context: SimulationNarrationContext,
): FallbackGenerationResult {
  const allowedSet = new Set(context.allowedEvidenceIds);

  const claims: AIExplanationClaimDto[] = [];
  const citedResults: BoundedSimulationNodeResult[] = [];
  const usedEvidenceIds = new Set<string>();
  let omittedWithoutEvidenceCount = 0;

  for (const item of context.results) {
    const validIds: string[] = [];
    const seenIds = new Set<string>();
    for (const id of item.evidenceIds) {
      if (allowedSet.has(id) && !seenIds.has(id)) {
        seenIds.add(id);
        validIds.push(id);
        if (validIds.length >= IMPACT_EXPLANATION_LIMITS.MAX_EVIDENCE_IDS_PER_CLAIM) {
          break;
        }
      }
    }

    if (validIds.length === 0) {
      omittedWithoutEvidenceCount += 1;
      continue;
    }

    if (claims.length < IMPACT_EXPLANATION_LIMITS.MAX_CLAIMS_COUNT) {
      const cappedNote = item.capped ? ", capped" : "";
      const claimText = truncateText(
        `Synthetic simulation state for node '${item.nodeId}': resultingState='${item.resultingState}' via rule '${item.ruleApplied}' at hopDistance=${item.hopDistance} (confidence ${item.confidence.toFixed(2)}${cappedNote}).`,
        IMPACT_EXPLANATION_LIMITS.MAX_CLAIM_TEXT_LENGTH,
      );

      claims.push({
        text: claimText,
        evidence_ids: validIds,
      });
      citedResults.push(item);
      for (const id of validIds) {
        usedEvidenceIds.add(id);
      }
    }
  }

  const abstained = allowedSet.size === 0 || claims.length === 0;
  const confidence = abstained
    ? "low"
    : deriveConfidence(citedResults, context, omittedWithoutEvidenceCount);
  const caveats = buildCaveats(context, omittedWithoutEvidenceCount, abstained);

  const m = context.executionMetrics;
  let summary: string;
  if (abstained) {
    summary = truncateText(
      `Synthetic simulation '${context.scenario.name}' (target '${context.scenario.targetNodeId}', failureType '${context.scenario.failureType}'): unable to provide an evidence-grounded narration because no verified simulation_state evidence records are available (${m.totalResults} deterministic result(s) recorded).`,
      IMPACT_EXPLANATION_LIMITS.MAX_SUMMARY_LENGTH,
    );
  } else {
    const parts = [
      `Deterministic synthetic simulation summary for '${context.scenario.name}' (target '${context.scenario.targetNodeId}', failureType '${context.scenario.failureType}'): ${m.failedCount} failed, ${m.degradedCount} degraded, ${m.atRiskCount} at_risk, and ${m.healthyCount} healthy across ${m.totalResults} total result(s) (max hop distance ${m.maxHopDistance}).`,
    ];
    if (context.truncated) {
      parts.push("Context was truncated; additional node results may exist.");
    }
    summary = truncateText(parts.join(" "), IMPACT_EXPLANATION_LIMITS.MAX_SUMMARY_LENGTH);
  }

  const output: AIExplanationOutputDto = {
    summary,
    claims: abstained ? [] : claims,
    confidence,
    caveats,
  };

  // Self-check invariant: fallback output must always satisfy the canonical validator
  const check = validateSimulationNarrationOutput(
    JSON.stringify(output),
    context.allowedEvidenceIds,
  );
  if (!check.success) {
    throw new Error(
      `Deterministic simulation fallback produced invalid output: ${check.errors.map((e) => e.code).join(", ")}`,
    );
  }

  return {
    output,
    schemaVersion: SIMULATION_NARRATION_OUTPUT_SCHEMA_VERSION,
    promptVersion: SIMULATION_FALLBACK_PROMPT_VERSION,
    abstained,
    usedEvidenceIds: Array.from(usedEvidenceIds),
    omittedWithoutEvidenceCount,
  };
}
